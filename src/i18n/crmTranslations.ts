import { STORAGE_KEYS } from '../data/seedData';
import type { Candidate, ResignationRecord } from '../types/crm';

export type UiLang = 'vi' | 'jp';

export function readStoredUiLang(): UiLang {
  try {
    const saved = localStorage.getItem(STORAGE_KEYS.UI_LANG);
    if (saved === 'jp' || saved === 'vi') return saved;
  } catch {
    // ignore storage errors
  }
  return 'vi';
}

export function saveStoredUiLang(lang: UiLang): void {
  try {
    localStorage.setItem(STORAGE_KEYS.UI_LANG, lang);
  } catch {
    // ignore storage errors
  }
}

export function getCandidateDisplayName(
  person: Partial<Candidate> | null | undefined,
  lang: UiLang = 'vi'
): string {
  const legal = String(person?.name || '').trim();
  if (legal && legal !== 'undefined' && legal !== 'null') return legal;
  const fb = String(person?.fbName || '').trim();
  if (fb && fb !== 'undefined' && fb !== 'null') return fb;
  return lang === 'jp' ? '名前未設定' : 'Chưa rõ tên';
}

export function getResignationDisplayName(
  record: Partial<ResignationRecord> | null | undefined,
  lang: UiLang = 'vi'
): string {
  const full = String(record?.fullName || '').trim();
  if (full && full !== 'undefined' && full !== 'null') return full;
  const fb = String(record?.fbName || '').trim();
  if (fb && fb !== 'undefined' && fb !== 'null') return fb;
  return lang === 'jp' ? '名前未設定' : 'Chưa rõ tên';
}

